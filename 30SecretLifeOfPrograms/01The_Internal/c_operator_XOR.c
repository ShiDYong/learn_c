#include<stdio.h>
#include <stdint.h>
#include <inttypes.h>

//定义权限掩码常量
//为什么用三位而不是四位原因：
//单比特表示单一权限：每种权限（读、写、执行）使用单独的一个比特来表示，可以使用位运算来组合和操作权限。例如：
//READ 使用最低有效位（第0位）
//WRITE 使用第二位（第1位）
//EXEC 使用第三位（第2位）
//便于组合和检查权限：通过位操作（如与、或、异或等），可以方便地组合多个权限、检查特定权限是否设置，或更改特定权限。
#define READ 0b001 //二进制的001
#define WRITE 0b010 //二进制的010
#define EXEC 0b100 //二进制的100

//函数原型
void toggle_permission(uint64_t *permissions, int file_id, int permission, int files_count);

void print_permissions(uint64_t permissions, int files_count);

int areEqual(int x, int y) {
    return (x ^ y) == 0;
}

int flipBit(int num, int pos) {
    return num ^ (1 << pos);
}

/*
 * 案例使用2:使用异或运算用来翻转一个整数的特定位
 * 在Linux系统中，文件权限通常由三组权限组成：读（r）、写（w）和执行（x），分别对应用户（owner）、组（group）和其他（others）。
 * 每组权限可以用一个三位的八进制数来表示，其中每一位分别代表读（4）、写（2）和执行（1）的权限。
 * 例如，如果一个文件的权限设置为755，这表示：
 * 用户拥有读、写和执行权限（7 = 4+2+1）
 * 组拥有读和执行权限（5 = 4+1）
 * 其他用户拥有读和执行权限（5 = 4+1）
 */
void permission() {
    // 用一个 64 位的无符号整数来表示所有文件的权限，
    // 每个文件用三个比特位来表示其权限（读、写、执行）
    uint64_t permissions = 0; //初始权限，所有文件都没有权限
    int files_count = 3;

    //给第一个文件设置读和执行权限
    toggle_permission(&permissions, 0, READ, files_count); //设置读权限
    toggle_permission(&permissions, 0, EXEC, files_count); //设置执行权限

    //给第二个文件设置读、写和执行权限
    toggle_permission(&permissions, 1, READ, files_count); //设置读权限
    toggle_permission(&permissions, 1, WRITE, files_count); //设置写权限
    toggle_permission(&permissions, 1, EXEC, files_count); //设置执行权限

    //给第三个文件设置写权限
    toggle_permission(&permissions, 2, WRITE, files_count); //设置写权限
    print_permissions(permissions, files_count);
}

/**
 *
 * @param permissions:指向存储所有文件权限的64位无符号整数的指针。
 * @param file_id:文件的唯一标识（索引），从0开始
 * @param permission:权限类型，使用预定义的常量 READ、WRITE、EXEC
 * @param files_count:文件总数
 * 优点和局限性
    优点：
    内存效率高：使用一个64位整数表示多个文件的权限。
    操作简洁：通过简单的位操作来设置和检查权限。
    局限性：
    文件数量受限：因为每个文件需要3位权限，64位整数最多能表示21个文件（64 / 3 = 21.33）。
    代码复杂度增加：位操作对初学者来说不直观，可能导致维护和理解上的困难。
 */
void toggle_permission(uint64_t *permissions, int file_id, int permission, int files_count) {
    if (file_id < 0 || file_id >= files_count) {
        printf("Error: file_id out of range of for the given number of files.\n");
        return;
    }
    //每个文件占用三个位：读、写和执行
    int bit_position = file_id * 3 + permission;

    //创建掩码，只有第bit_position位是1
    //通过左移操作创建掩码，使得只有目标位为1，其它位为0。
    // 1ULL表示无符号长整数1，通过左移bit_position位得到掩码
    uint64_t mask = 1ULL << bit_position;
    //执行异或运算翻转第bit_position位
    *permissions ^= mask;
    /*
    1.设置第一个文件的读权限：
     toggle_permission(&permissions, 0, READ, files_count);
     file_id = 0, permission = READ
     bit_position = 0 * 3 + 0 = 0
     mask = 1ULL << 0 = 0b0001
     *permissions ^= 0b0001 结果 permissions = 0b0001
     2.设置第一个文件的执行权限：
     toggle_permission(&permissions, 0, EXEC, files_count);
     file_id = 0, permission = EXEC
     bit_position = 0 * 3 + 2 = 2
     mask = 1ULL << 2 = 0b0100
     *permissions ^= 0b0100 结果 permissions = 0b0101
     3.设置第二个文件的写权限：
     toggle_permission(&permissions, 1, WRITE, files_count);
      file_id = 1, permission = WRITE
      bit_position = 1 * 3 + 1 = 4
      mask = 1ULL << 4 = 0b10000
      *permissions ^= 0b10000 结果 permissions = 0b10101
     */

}
/**
 * 函数的作用是打印每个文件的权限
 * @param permissions：表示所有文件权限的位掩码
 * @param files_count：表示文件的数量
 */
void print_permissions(uint64_t permissions, int files_count) {
    /*
    在 permissions 中，每3位表示一个文件的权限，多个文件的权限信息按顺序依次存储。
    例如，对于3个文件的权限，位掩码可能是 000000000000000000000000000111，其中：
    第0-2位表示第一个文件的权限
    第3-5位表示第二个文件的权限
    第6-8位表示第三个文件的权限
     */
    for (int i = 0; i < files_count; i++) {
        printf("File %d permissions: ", i);
        //i * 3 + 2 计算出第i个文件的读权限所在的位位置。
        //1ULL << (i * 3 + 2) 创建一个掩码，将1左移到读权限的位位置。
        //permissions & 掩码 检查该位是否为1，若为1则表示有读权限
        if (permissions & (1ULL << (i * 3 + 2))) {
            printf("READ ");
        }
        /*
         * 在位操作中，非零值在布尔上下文中被视为“真”，而零值被视为“假”。所以，
         * 当我们使用 if 语句检查 (permissions & (1ULL << (i * 3 + 0))) 是否为零时，实际上我们是在检查特定位是否为零。
           在这个特定的位操作中，我们使用位掩码 (1ULL << (i * 3 + 0)) 来检查权限位是否为 1。如果权限位为 1，则执行权限被设置，
           因此表达式的结果将是非零值（1），如果权限位为 0，则表达式的结果将是零值。因此，当权限位被设置时，
           表达式的结果是非零的，因此 if 语句将执行相应的代码块。
           这种方法是有效的，因为我们只对特定的权限位感兴趣，而不是整个 permissions 位掩码。
           所以，通过检查权限位是否为零，我们能够判断该权限是否被设置，从而决定是否输出相应的权限信息。
           虽然我们没有显式地检查结果是否为非零值，但在 C 语言中，非零值被视为“真”，
           因此 if 语句将根据结果是非零还是零来决定执行哪个代码块
         */
        if (permissions & (1ULL << (i * 3 + 1))) {
            printf("WRITE ");
        }
        if (permissions & (1ULL << (i * 3 + 0))) {
            printf("EXEC ");
        }
        printf("\n");
    }
}

int main() {
    //1.使用异或运算可以在不使用临时变量的情况下交换两个整数变量的值，
    //利用上述特性1和2:异或操作的对称性和自反性
    //相反性（逆元）是指对于任意数 x，存在一个数 y，使得 x ^ y = 0。在代码中，
    // 通过连续两次异或操作，a 和 b 交换了它们的值，同时保持了原始值
    //可以根据特性的公式进行计算化简单就会容易理解很多
    int a = 5; //1101
    int b = 9; //1001
    a = a ^ b;
    // a = 0101 ^ 1001 = 1100 （a 现在包含 a ^ b 的结果）
    // 此时：a = 12（二进制：1100），b = 9（二进制：1001）
    b = a ^ b;
    /**
      b = 1100 ^ 1001 = 0101（利用对称性：a ^ b = b ^ a）
     因为 a = a ^ b 的结果是 a ^ b，现在 b = a ^ b ^ b，利用自反性 b ^ b = 0，因此 b = a。
     此时：a = 12（二进制：1100），b = 5（二进制：0101）
     进一步理解：
     b 现在等于 a ^ b，并且 a 当前是 a ^ b（经过第一步的计算）。
     于是：
     新的 b 值实际上是 (a ^ b) ^ b。
     根据异或运算的性质，(a ^ b) ^ b 就等于 a（因为 b ^ b = 0，且 a ^ 0 = a）。
     因此在第二步中：
     b 被赋值为 原始的 a 的值，即 5
     备注：在运算过程中区分新旧a、b。
     */
    a = a ^ b;
    /**
     * 此时，a 的值是 12（1100），b 的值是 5（0101）。我们将它们进行异或：
    a ^ b 等于 12 ^ 5：
    1100（当前 a 的值）
    0101（当前 b 的值）
    结果：1001（二进制）
    为什么 a = (a ^ b) 等于原始的 b？
     这是因为：
    a 现在等于 原始的 a ^ b。
    新的 a 值实际上是 (原始的 a ^ b) ^ 原始的 a。
    根据异或运算的性质，(a ^ b) ^ a 就等于 b（因为 a ^ a = 0，且 0 ^ b = b）。
    因此在第三步中：
    a 被赋值为 原始的 b 的值，即 9。
     */
    /**
     * ### 总结
    经过三次异或运算，变量 `a` 和 `b` 的值成功交换。这段代码体现了异或运算的对称性和自反性：
    1. **对称性** 使得 `a ^ b` 和 `b ^ a` 相等，确保运算的结果与操作数的顺序无关。
    2. **自反性** 确保在第二步和第三步中，通过两次与同一个数的异或操作，可以恢复另一个数的原始值。
    因此，这段代码利用了这些性质，巧妙地交换了两个变量的值，而无需使用额外的临时变量。
     */

    printf("a = %d, b = %d\n", a, b); // 输出：a = 9, b = 5

    //2.判断两个数是否相等，异或运算的结果为0，只有两个操作数相等。利用
    //这一行性质，可以用来判断两个数是否相等
    int c = 5;
    printf("a and b are equal: %s\n", areEqual(a, b) ? "true" : "false");
    printf("b and c are equal: %s\n", areEqual(b, c) ? "true" : "false");

    /**
     * 3.翻转特定位：
     * 在计算机科学中，"翻转"（或称为"取反"、"反转"）一个整数的特定位通常意味着改变该位的值。如果该位是0，翻转后变为1；
     * 如果该位是1，翻转后变为0。这种操作在位操作中非常常见，因为它可以用于切换状态、设置或清除标志位等。
     * 掩码（Mask）在计算机科学和编程中是一个用于控制位操作的二进制数。掩码通常用来屏蔽（即选择性地忽略或关注）数据的某些部分，
     * 以便在执行位操作时只影响或检查特定的位
     * 掩码的作用：
       选择性操作：掩码允许程序员只对数据的某些位进行操作，而不影响其他位。这在处理二进制数据时非常有用，尤其是在需要同时操作多个字段或标志位时。
       数据隔离：通过掩码，可以将数据的某些部分隔离开来，以便独立地处理这些部分。例如，在处理网络掩码时，可以隔离出网络地址和主机地址。
       条件修改：掩码可以用来根据特定条件修改数据。只有与掩码中相应的位相匹配的位才会被修改，其他位保持不变。
       状态标志：在某些算法或系统中，掩码可以用于表示状态或属性的存在与否。例如，权限系统中的每个位可以代表不同的权限。
       为什么需要掩码：
       效率：位操作通常比标准的算术或逻辑操作更快，因为它们直接在硬件层面上执行。
       控制：掩码提供了一种精确控制数据位的方法，这对于低级编程和系统编程尤为重要。
       简洁性：使用掩码可以使代码更加简洁和易于理解，尤其是当涉及到复杂的位模式时。
       硬件交互：在与硬件交互时，掩码经常用于配置和控制硬件设备的行为。
       数据编码：在数据编码和解码过程中，掩码可以帮助识别和提取特定的数据字段。
       结合掩码来理解翻转操作：
       创建掩码：首先，确定要翻转的位的位置，然后创建一个掩码，该掩码在该特定位置有一个1，其余位都是0。
       例如，要翻转第3位（从0开始计数），掩码将是 00001000（二进制），可以通过表达式 1 << 3 来创建。
       执行异或运算：接下来，将这个掩码与目标整数进行异或运算。异或运算的性质是，当两个对应的位相同，结果是0；
       当两个对应的位不同，结果是1。因此，当掩码的某一位为1时，它将与目标整数中对应位的值进行异或运算，从而翻转该位的值。
       结果：异或运算完成后，目标整数中只有与掩码中的1对应的位被翻转，其他位保持不变。
     */
    int num = 0b00101010; //目标整数
    int mask = 1 << 3;     //创建掩码，翻转第3位
    num = num ^ mask;     //执行异或运算
    /*
      00101010 (原始 num)
    ^ 00001000 (掩码)
      -----------
      00100010 (异或结果)
     */
    //执行异或运算后：
    //num 的第3位（从0开始计数）将被翻转。如果原来是0，现在变为1；如果原来是1，现在变为0。
    //num 的其他位保持不变。
    //在这个例子中，num 的原始值 00101010 经过翻转第3位后变为 00100010。
    return 0;

}